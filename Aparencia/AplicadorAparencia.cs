    public static void Aplicar(PreferenciasAparencia preferencias)
    {
        var app = Application.Current ?? throw new InvalidOperationException("Aplicação não inicializada.");
        app.RequestedThemeVariant = preferencias.Modo == ModoVisual.Claro ? ThemeVariant.Light : ThemeVariant.Dark;
        var resolvida = ResolvedorAparencia.Resolver(preferencias);
        foreach (var (chave, cor) in resolvida.Recursos) app.Resources[chave] = Brush.Parse(cor);
        foreach (var chave in RecursosFluent)
        {
            var token = TokenFluent(chave);
            app.Resources[chave] = chave == "ScrollBarThumbBackgroundColor" ? Color.Parse(resolvida.Recursos[token]) : token == "Preto" ? Brushes.Black : token == "Branco" ? Brushes.White : Brush.Parse(resolvida.Recursos[token]);
        }
        foreach (var chave in new[] { "SystemAccentColor", "SystemAccentColorDark1", "SystemAccentColorDark2", "SystemAccentColorDark3", "SystemAccentColorLight1", "SystemAccentColorLight2", "SystemAccentColorLight3" })
            app.Resources[chave] = Color.Parse(resolvida.Recursos["AccentBrush"]);
    }
    private static string TokenFluent(string chave)
    {
        if (chave.Contains("FocusVisualPrimary")) return "Preto";
        if (chave.Contains("FocusVisualSecondary")) return "Branco";
        if (chave.Contains("Error")) return "ErrorOnPanel";
        if (chave.Contains("Disabled")) return chave.Contains("Border") ? "ControlBorder" : chave.Contains("Foreground") || chave.Contains("Glyph") || chave.Contains("Arrow") ? "DisabledForeground" : "DisabledBackground";
        if (chave.StartsWith("CheckBoxForeground")) return "ControlForeground";
        var selecionado = chave.Contains("Selected") || chave.Contains("Checked") && !chave.Contains("Unchecked") || chave.Contains("Indeterminate") || chave.Contains("HighlightList") || chave.Contains("SelectionHighlight");
        if (chave.Contains("HighlightAltBase")) return "AccentForeground";
        if (selecionado) return chave.Contains("Foreground") || chave.Contains("Glyph") ? "AccentForeground" : "AccentBrush";
        if (chave.StartsWith("AccentButton")) return chave.Contains("Foreground") ? "AccentForeground" : chave.Contains("Border") ? "FocusBrush" : "AccentBrush";
        if (chave.StartsWith("Button")) return chave.Contains("Border") ? "ButtonFocus" :
            chave.Contains("Foreground") ? chave.Contains("PointerOver") ? "ButtonHoverText" : chave.Contains("Pressed") ? "ButtonPressedText" : "ButtonForeground" :
            chave.Contains("PointerOver") ? "ButtonHover" : chave.Contains("Pressed") ? "ButtonPressed" : "ButtonBackground";
        if (chave.Contains("Border") || chave.Contains("Stroke")) return chave.Contains("Focused") ? "FocusBrush" : "ControlBorder";
        if (chave.Contains("Foreground") || chave.Contains("Glyph") || chave.Contains("Arrow") || chave.Contains("Thumb"))
            return chave.Contains("PointerOver") || chave.Contains("Pressed") ? "PanelHoverText" : "ControlForeground";
        return chave.Contains("PointerOver") || chave.Contains("Pressed") ? "PanelHover" : "ControlBackground";
    }
